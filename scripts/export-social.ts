/**
 * Builds the social content files from the real banks, so posts never drift from the app.
 *   npx tsx scripts/export-social.ts
 * Writes social/week1/deep-scan.json, what-has-more.json and social/week1/README.md.
 * Each item keeps the post (safe to publish on the day) apart from the reveal (publish the NEXT day).
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { deepDivePromptsExpanded } from "../src/dataDeepDiveExtra";
import { higherLowerPairs } from "../src/dataExtra";
import { hashSeed, seeded, shuffle } from "../src/lib";
import { deepDivePointsByTier } from "../src/arcadeLogic";

const TIERS = ["Skin deep", "Subcutaneous", "Fascia", "Muscle", "Bone", "Marrow"];
const WEEKDAYS = ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"];
const addDays = (d: string, n: number) => new Date(Date.parse(d + "T00:00:00Z") + n * 86400000).toISOString().slice(0, 10);
const weekday = (d: string) => WEEKDAYS[new Date(d + "T00:00:00Z").getUTCDay()];

/** Hand-picked for recognition and fun; ids are the bank's own. */
const SCAN_SLATE: [string, string][] = [
  ["2026-11-24", "d50"], // drug-induced lupus
  ["2026-11-25", "d05"], // urease organisms
  ["2026-11-26", "d36"], // serotonin syndrome
  ["2026-11-27", "d30"], // foodborne illness / neurotoxins
  ["2026-11-28", "d32"], // granulomas
  ["2026-11-29", "d17"], // autoantibodies
  ["2026-11-30", "d23"]  // QT-prolonging classes
];
const PAIR_SLATE: [string, string][] = [
  ["2026-11-24", "Red blood cells your marrow makes each second"],
  ["2026-11-26", "Radiation dose from one chest X-ray"],
  ["2026-11-28", "Bacteria in the human gut"]
];

const inAppSeven = (date: string) => shuffle(deepDivePromptsExpanded, seeded(hashSeed(date + "|general|dive") + 811)).slice(0, 7).map((p) => p.id);

const scans = SCAN_SLATE.map(([date, id]) => {
  const p = deepDivePromptsExpanded.find((x) => x.id === id);
  if (!p) throw new Error("Missing prompt " + id);
  const tiers = TIERS.map((name, i) => ({
    tier: i + 1, name, points: deepDivePointsByTier[i],
    answers: p.answers.filter((a) => a.tier === i + 1).map((a) => a.answer)
  }));
  if (tiers.some((t) => !t.answers.length)) throw new Error(id + " has an empty tier");
  return {
    date, weekday: weekday(date), id,
    post: {
      publishOn: date,
      prompt: p.prompt,
      caption: "Today's scan. One prompt, one answer. Rarer answer, deeper layer. Drop ONE answer in the comments. The deepest valid answer gets credited in tomorrow's reveal. Layers come from our question bank, not from other players. Seven new scans every day in Roundsy."
    },
    reveal: {
      publishOn: addDays(date, 1),
      tiers,
      explanation: p.explanation,
      rule: "Answers not on this key are judge's call and are placed in the next day's reveal.",
      caption: "Yesterday's scan: " + p.prompt + " How deep did you go?"
    },
    inTodaysAppSet: inAppSeven(date).includes(id)
  };
});

const pairs = PAIR_SLATE.map(([date, prefix]) => {
  const q = higherLowerPairs.find((x) => "fun" in x && x.a.startsWith(prefix));
  if (!q) throw new Error("Missing pair " + prefix);
  return {
    date, weekday: weekday(date),
    post: { publishOn: date, question: "Which has more?", a: q.a, b: q.b, unit: q.unit },
    reveal: { publishOn: addDays(date, 1), answer: q.av > q.bv ? "A" : "B", a: q.av, b: q.bv, explanation: q.explanation, source: q.source }
  };
});

mkdirSync("social/week1", { recursive: true });
writeFileSync("social/week1/deep-scan.json", JSON.stringify(scans, null, 2) + "\n");
writeFileSync("social/week1/what-has-more.json", JSON.stringify(pairs, null, 2) + "\n");

const md: string[] = ["# Roundsy social, week 1 (Nov 24 to Nov 30, 2026)", "",
  "Generated by `npx tsx scripts/export-social.ts` from the real banks. Each item has a **POST** (publish on the day) and a **REVEAL** (publish the next day). Never publish a reveal with its post.", "",
  "Note: the post's prompt is a real Deep Scan prompt but is not necessarily one of that day's seven in-app scans (see `inTodaysAppSet` in the JSON). The caption says \"seven new scans every day in Roundsy\" rather than promising this exact prompt.", ""];
for (const s of scans) {
  md.push("## " + s.weekday + " " + s.date + ": Deep Scan", "", "**POST (" + s.post.publishOn + "):** " + s.post.prompt, "", "> " + s.post.caption, "", "**REVEAL (" + s.reveal.publishOn + "):**", "");
  for (const t of s.reveal.tiers) md.push("- " + t.name + " (" + t.points + "): " + t.answers.join(", "));
  md.push("", s.reveal.explanation, "", "_" + s.reveal.rule + "_ In today's in-app set: " + (s.inTodaysAppSet ? "yes" : "no"), "");
}
for (const q of pairs) {
  md.push("## " + q.weekday + " " + q.date + ": What Has More?", "", "**POST:** A) " + q.post.a, "", "B) " + q.post.b, "", "**REVEAL (" + q.reveal.publishOn + "):** " + q.reveal.answer + " (" + q.reveal.a + " vs " + q.reveal.b + " " + q.post.unit + "). " + q.reveal.explanation, "");
}
writeFileSync("social/week1/README.md", md.join("\n"));
console.log("Wrote " + scans.length + " scans and " + pairs.length + " pairs to social/week1/");
